-- Living In Concord NC — database schema
-- ============================================================================
-- Derived from helpers/schema.tsx (kysely-codegen output for the original
-- Floot database) cross-checked against the queries in endpoints/.
--
-- Conventions:
--   * Table and column names are snake_case; the app's Kysely CamelCasePlugin
--     (helpers/db.tsx) maps them to the camelCase names used in TypeScript.
--   * Every column typed `Generated<T>` in helpers/schema.tsx has a database
--     default here (now(), identity, or a literal), matching codegen output.
--   * `id` columns use GENERATED BY DEFAULT AS IDENTITY so seed scripts may
--     insert the explicit ids captured from the live site (the seed script
--     resets the sequences afterwards).
--   * Enum types mirror the TypeScript union types in helpers/schema.tsx.
--   * Uniqueness assumptions (lookups in endpoints/ rely on these being
--     single-row): blog_posts.slug, neighborhoods.slug, users.email,
--     site_settings.setting_key.
--
-- Apply with:  psql "$DATABASE_URL" -f db/schema.sql
-- ============================================================================

BEGIN;

CREATE TYPE blog_category AS ENUM (
  'buying_tips',
  'lifestyle',
  'market_updates',
  'neighborhood_guides',
  'relocation',
  'selling_tips'
);

CREATE TYPE user_role AS ENUM ('admin', 'user');

-- ---------------------------------------------------------------------------
-- Content
-- ---------------------------------------------------------------------------

CREATE TABLE blog_posts (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        text NOT NULL,
  slug         text NOT NULL UNIQUE,
  excerpt      text NOT NULL,
  content      text NOT NULL,
  category     blog_category NOT NULL,
  image_url    text,
  author       text NOT NULL DEFAULT 'Franklin Bellamy',
  published_at timestamptz NOT NULL DEFAULT now(),
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE neighborhoods (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              text NOT NULL,
  slug              text NOT NULL UNIQUE,
  description       text NOT NULL,
  rating            numeric NOT NULL DEFAULT 0,
  price_range_min   integer NOT NULL,
  price_range_max   integer NOT NULL,
  tags              text[] NOT NULL DEFAULT '{}',
  image_url         text,
  highlights        text,
  youtube_video_url text,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE testimonials (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_name text NOT NULL,
  location    text NOT NULL,
  content     text NOT NULL,
  rating      integer NOT NULL DEFAULT 5,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE market_data (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month             integer NOT NULL CHECK (month BETWEEN 1 AND 12),
  year              integer NOT NULL,
  median_price      integer NOT NULL,
  homes_sold        integer NOT NULL,
  avg_days_on_market integer NOT NULL,
  active_listings   integer NOT NULL,
  price_change_yoy  numeric NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Lead capture
-- ---------------------------------------------------------------------------

CREATE TABLE contact_submissions (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name           text NOT NULL,
  email               text NOT NULL,
  phone               text,
  interested_in       text,
  message             text,
  budget              text,
  timeline            text,
  motivation          text,
  preferred_call_time text,
  qualifier_variant   text,
  source_neighborhood text,
  created_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE guide_downloads (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  text NOT NULL,
  email      text NOT NULL,
  phone      text,
  moving_from text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE home_valuation_requests (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name        text NOT NULL,
  email            text NOT NULL,
  phone            text,
  property_address text NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE market_update_signups (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name  text NOT NULL,
  email      text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Relocation guide PDF (stored base64 in chunks, served by endpoints/guide)
-- ---------------------------------------------------------------------------

CREATE TABLE guide_pdf_chunks (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_index integer NOT NULL,
  chunk_data  text NOT NULL,
  created_at  timestamptz DEFAULT now()
);

CREATE TABLE site_settings (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_key   text NOT NULL UNIQUE,
  setting_value text,
  updated_at    timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Auth (users, password hashes, sessions, login audit)
-- ---------------------------------------------------------------------------

CREATE TABLE users (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email        text NOT NULL UNIQUE,
  display_name text NOT NULL,
  avatar_url   text,
  role         user_role NOT NULL DEFAULT 'user',
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE user_passwords (
  user_id       integer PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
  password_hash text NOT NULL
);

CREATE TABLE sessions (
  id            text PRIMARY KEY,
  user_id       integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at    timestamptz NOT NULL DEFAULT now(),
  last_accessed timestamptz NOT NULL DEFAULT now(),
  expires_at    timestamptz NOT NULL
);

CREATE INDEX sessions_user_id_idx ON sessions (user_id);

CREATE TABLE login_attempts (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       text NOT NULL,
  success     boolean NOT NULL DEFAULT false,
  attempted_at timestamptz DEFAULT now()
);

CREATE INDEX login_attempts_email_idx ON login_attempts (email);

COMMIT;
