import { Hono } from 'hono'

// Shared Hono app: all /_api endpoint routes.
// Used by server.ts for local development and by api/index.ts (Vercel
// serverless function) in production, so both environments dispatch
// identically. Static-file serving and the SPA fallback live in server.ts
// (local) and vercel.json rewrites (production) respectively.
const app = new Hono();


app.post('_api/chat',async c => {
  try {
    const { handle } = await import("./endpoints/chat_POST.js");
    let request = c.req.raw;
    const response = await handle(request);
    if (!(response instanceof Response) && response.constructor.name !== "Response") {
      return c.text("Invalid response format. handle should always return a Response object." + response.constructor.name, 500);
    }
    return response;
  } catch (e) {
    console.error(e);
    return c.text("Error loading endpoint code " + e.message,  500)
  }
})
